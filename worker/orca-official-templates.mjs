let cachedOfficial = null;

function buildOfficialItem(tpl, orcaBin) {
  const avatarDataUrl =
    renderMascotAvatarDataUrl(tpl.mascot || "A1", tpl.color || "#b3dbf4", orcaBin) ||
    renderEmojiAvatarDataUrl("🤖", tpl.color || "#334155") ||
    "";
  const tags = [...(tpl.connectors || []), ...(tpl.skills || [])].slice(0, 5);
  return {
    id: `official_${tpl.id}`,
    kind: "official",
    templateId: tpl.id,
    shareId: "",
    shareUrl: "",
    deepLink: "",
    name: tpl.nameEn,
    nameZh: tpl.nameZh,
    nameEn: tpl.nameEn,
    purpose: tpl.purposeEn,
    purposeZh: tpl.purposeZh,
    purposeEn: tpl.purposeEn,
    description: "",
    watches: tpl.watches || "",
    doesText: tpl.does || "",
    reports: tpl.reports || "",
    connectors: tpl.connectors || [],
    skills: tpl.skills || [],
    category: tpl.category || "general",
    tags,
    agentHint: "claude",
    avatarType: "mascot",
    avatarValue: tpl.mascot || "A1",
    avatarColor: tpl.color || "#b3dbf4",
    avatarDataUrl,
    authorName: "Orca Official",
    trust: "official",
    featured: tpl.id === "pr-review" || tpl.id === "bug-investigation" || tpl.id === "release",
    likesCount: 0,
    hiresCount: 0,
    liked: false,
    createdAt: 0,
  };
}

export function collectOfficialMarketTemplates(orcaBin = "") {
  if (cachedOfficial) return cachedOfficial;
  cachedOfficial = OFFICIAL_SEED.map((tpl) => buildOfficialItem(tpl, orcaBin));
  return cachedOfficial;
}

export function hasLocalOfficialCatalog(orcaBin = "") {
  if (!orcaBin || !path.isAbsolute(orcaBin)) return false;
  const dir = path.resolve(path.dirname(orcaBin), "..", "app.asar.unpacked", "out", "shared", "bots", "bot-template-catalog");
  return fs.existsSync(dir);
}
